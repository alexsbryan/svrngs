# usage: python3 -I figures.py <run-dir>
# Reads <run-dir>/<app>/windows.json (from analyze.py) for n8n, kuma, owui and
# prints table.md: every window, then (a) today's design and (b) the fix, per
# app. Window 2->3 holds the light use (run.sh starts it at minute 12); the
# other five are idle.
#
# (a) Today: each copy is one tar per state volume, and the group's folder
#     sends every new tar whole to every member. Files move by hash, so a tar
#     byte-identical to the one before would move nothing; "measured" counts
#     only the tars that differed, "nominal" all 12 an hour. Group of 20.
# (b) The fix: a copy is one blob per file plus a manifest; only blobs not
#     already held move, and only to the computers that keep (3 holders).
#     Per window: the bytes of changed and added files, plus the manifest when
#     anything changed. "4 KiB" is the same with each changed file sent as its
#     differing 4 KiB blocks, a candidate for shrinking it further.
import json
import os
import sys

run = sys.argv[1]
APPS = [("n8n", "n8n"), ("kuma", "Uptime Kuma"), ("owui", "Open WebUI")]
LIGHT = "2->3"
MEMBERS, HOLDERS, PER_HOUR = 20, 3, 12
MB = 1e6


def mb(x):
    return f"{x / MB:.3f}" if x < 10 * MB else f"{x / MB:.1f}"


def rate(per_window):  # bytes a window -> (MB/hour, GB/day) for one receiver
    h = per_window * PER_HOUR / MB
    return h, h * 24 / 1000


out = ["# Copy churn: the windows", "",
       "Generated by `python3 -I scripts/figures.py .` from each app's `windows.json`",
       "(`scripts/analyze.py`). A window is the 5 minutes between two consecutive copies;",
       f"window {LIGHT} holds the one light use, the rest are idle. Bytes are decimal MB.", ""]
summary = []
for app, title in APPS:
    w = json.load(open(os.path.join(run, app, "windows.json")))
    copies = {c["tar"]: c for c in w["copies"]}
    out += [f"## {title}", "",
            "| window | kind | tar MB (after) | tar same bytes | files changed / added / removed | MB changed + added | MB in changed 4 KiB blocks + added | header-only entries | order changed | manifest KB |",
            "|---|---|---|---|---|---|---|---|---|---|"]
    rows = []
    for d in w["windows"]:
        after = copies[f"snaps/{d['window'].split('->')[1]}.tar"]
        moved = d["bytes_changed"] + d["bytes_added"]
        anything = bool(d["changed"] or d["added"] or d["removed"])
        man = after["manifest_bytes"] if anything else 0
        rows.append((d["window"], d["window"] == LIGHT, after["bytes"], d["tar_identical"], moved + man,
                     d["bytes_changed_blocks"] + d["bytes_added"] + man))
        out.append(f"| {d['window']} | {'light use' if d['window'] == LIGHT else 'idle'} | {mb(after['bytes'])} | "
                   f"{'yes' if d['tar_identical'] else 'no'} | {len(d['changed'])} / {len(d['added'])} / "
                   f"{len(d['removed'])} | {mb(moved)} | {mb(d['bytes_changed_blocks'] + d['bytes_added'])} | "
                   f"{len(d['header_only'])} | {'yes' if d['order_changed'] else 'no'} | {man / 1000:.1f} |")
    out.append("")
    out.append("Changed files, per window (path, size before → after, differing 4 KiB blocks):")
    out.append("")
    for d in w["windows"]:
        parts = [f"`{p}` {mb(a)}→{mb(b)} MB, {n} blocks" for p, a, b, n in d["changed"]]
        parts += [f"added `{p}` {mb(s)} MB" for p, s in d["added"]]
        parts += [f"removed `{p}`" for p, s in d["removed"]]
        out.append(f"- {d['window']}: " + ("; ".join(parts) if parts else "nothing"))
    out.append("")
    tar = sum(c["bytes"] for k, c in copies.items() if k.startswith("snaps/")) / 7
    differ = sum(not r[3] for r in rows) / len(rows)
    idle = [r for r in rows if not r[1]]
    light = [r for r in rows if r[1]]
    summary.append((title, tar, differ, sum(r[4] for r in idle) / len(idle), max(r[4] for r in idle),
                    light[0][4], sum(r[5] for r in idle) / len(idle), light[0][5]))

out += ["## (a) and (b)", "",
        f"(a) today: each copy's tar, whole, to each of {MEMBERS} members, {PER_HOUR} copies an hour. "
        "Nominal: every tar moves. Measured: a tar byte-identical to the one before moves nothing "
        "(files move by hash), so only the tars that differed in this run count.",
        f"(b) the fix: per copy, the changed and added files plus the manifest (only when anything changed), "
        f"to each of {HOLDERS} holders. Idle: the mean of the five idle windows, × {PER_HOUR} an hour. "
        "Light use: the one window that held it, in MB per holder (one use costs this once).", "",
        "| app | mean tar MB | tars that differed | (a) nominal, per member MB/h | (a) nominal, 20 members GB/day | (a) measured, per member MB/h | (a) measured, 20 members GB/day | (b) idle, per holder MB/h | (b) idle, 3 holders GB/day | (b) light-use window, MB per holder | (b) idle, 4 KiB blocks, per holder MB/h | (b) light-use window, 4 KiB blocks, MB per holder |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|"]
for title, tar, differ, idle, worst, light, idle_blk, light_blk in summary:
    n_h, n_d = rate(tar)
    a_h, a_d = rate(tar * differ)
    b_h, b_d = rate(idle)
    out.append(f"| {title} | {mb(tar)} | {differ * 6:.0f} of 6 | {n_h:.1f} | {n_d * MEMBERS:.1f} | {a_h:.1f} | "
               f"{a_d * MEMBERS:.1f} | {b_h:.2f} | {b_d * HOLDERS:.3f} | {light / MB:.3f} | {rate(idle_blk)[0]:.2f} | "
               f"{light_blk / MB:.3f} |")
print("\n".join(out))
